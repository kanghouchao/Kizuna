package com.kizuna.point.domain;

/**
 * 特典規則の条件種別。閉じた三種で、自由な条件式は持たない。
 *
 * <p>取消方法はこの種別から導く（列に物化しない）— 受注を条件とする {@link #REFERRAL} / {@link #VISIT} の付与は根拠受注に連動して取り消され、{@link
 * #LOGIN} の付与に取消は無い。非法な組合せ（ログイン × 受注連動）を作れる自由フィールドにしないための設計である。
 */
public enum BenefitRuleType {
  /** 紹介。被紹介者の初回有料受注完了を条件に紹介者・被紹介者の双方へ付与する。 */
  REFERRAL,
  /** ログイン。発火事象が店舗文脈を持たないため、全店舗の規則しか取れない。 */
  LOGIN,
  /** 来店。会員へ帰属した受注の完了を条件に付与する。 */
  VISIT
}
