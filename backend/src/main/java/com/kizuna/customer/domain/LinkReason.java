package com.kizuna.customer.domain;

/**
 * 関連（会員と店舗顧客台帳の紐づけ）の成立根拠。「どの機構で成立したか」という事実であり、確度の抽象等級ではない — 等級が要る日が来ても機構名から導出できる（逆は不可逆）。
 *
 * <p>根拠は行ごとに不変の純記録で、値によって挙動を分けない（MIGRATION の関連も全機能で働く）。より強い根拠での再成立は、解除して新しい行を作ることで表す。
 */
public enum LinkReason {
  /** 会員コードの提示による店舗の明示操作。 */
  MEMBER_CODE,

  /** 会員申請の受注を確定した際の自動整備。書き手は確定時自動整備の実装で加わる。 */
  MEMBER_REQUEST,

  /** 旧システムからの移行由来。書き手は移行の受け入れ実装で加わる。 */
  MIGRATION
}
