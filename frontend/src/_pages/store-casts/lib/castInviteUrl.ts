/**
 * キャスト招待の受諾 URL（店舗が招待相手へ配る値）。
 *
 * トークンはフラグメントに置く。パスも問い合わせ文字列もリクエストターゲットとして送られ、
 * リバースプロキシとアプリのアクセスログに 72 時間有効の生値がそのまま残る — 招待が開かれる
 * たびにログへクレデンシャルを書くことになる。所持だけで受諾が通る資格情報のため、フラグメント
 * （サーバへ送られない）に載せ、受諾画面がブラウザ側で読み取って照会・受諾要求の本体に移す。
 *
 * ホストは現在のオリジンをそのまま使う。受諾ページは平台ドメイン側の体裁だが、隣の
 * getPlatformDomain() は NEXT_PUBLIC_PLATFORM_DOMAIN のビルド時置換に依存しており、
 * ビルドへ渡していない現状ではブラウザ上で常に既定値へ落ちる。店舗別ドメインで発行した招待は
 * そのドメインを指すが、/platform/* はどのホストでも同じアプリが応答するため受諾は成立する。
 *
 * 末尾のスラッシュは付けない — 付けると 308 で落とされた URL を招待相手へ配ることになる。
 */
export function castInviteUrl(token: string): string {
  return `${window.location.origin}/platform/invite#${encodeURIComponent(token)}`;
}
